#!/usr/bin/env node
// Regenerates scripts/lib/banned-hashes.mjs from the gitignored .banned-terms.local list, HMAC-keyed by .banned-key.local.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { normalizeForBan, hashTerm, MAX_N } from "./lib/banned.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const keyPath = join(root, ".banned-key.local");
if (!existsSync(keyPath)) {
  throw new Error('Missing .banned-key.local; generate one with: node -e "console.log(require(\'crypto\').randomBytes(32).toString(\'hex\'))" > .banned-key.local');
}
const key = readFileSync(keyPath, "utf8").trim();
const terms = readFileSync(join(root, ".banned-terms.local"), "utf8").split("\n").map((s) => s.trim()).filter(Boolean);
for (const t of terms) {
  const tokenCount = normalizeForBan(t).split(" ").filter(Boolean).length;
  if (tokenCount > MAX_N) throw new Error(`A banned term normalizes to ${tokenCount} tokens, more than MAX_N (${MAX_N})`);
}
const hashes = [...new Set(terms.map((t) => hashTerm(normalizeForBan(t), key)))].sort();
const body = `// Generated by scripts/hash-banned-terms.mjs; HMAC-SHA256 of normalized banned n-grams, keyed by .banned-key.local.\nexport const BANNED_HASHES = new Set(${JSON.stringify(hashes, null, 2)});\n`;
writeFileSync(join(root, "scripts/lib/banned-hashes.mjs"), body);
console.log(`Wrote ${hashes.length} hashes.`);
